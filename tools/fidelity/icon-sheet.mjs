#!/usr/bin/env node
// The icon sheet: every `Glyph` of the kit at 16 and 20 plus the web chrome's call-site sizes, on
// the design's ground (abyss), one 64 px cell each. The sheet exists twice and is scored per cell:
//   web     a static page with the markup of browser/icons.tsx `Icon` (svg, viewBox 24, stroke 1.7,
//           round caps and joins, currentColor), shot in headless Chromium at DPR 1 and 2;
//   wubble  crates/wubble-ui/tests/icon-sheet.slint (generated here: one kit `Icon` per cell),
//           rendered by `WUBBLE_ICON_SHEET=DIR cargo test -p wubble-ui --test icon_sheet`.
//
//   node tools/fidelity/icon-sheet.mjs emit                 write the .slint and DIR/cells.json
//   node tools/fidelity/icon-sheet.mjs web DIR              DIR/web-{1,2}x.png
//   node tools/fidelity/icon-sheet.mjs score DIR            per-cell SSIM of DIR/web vs DIR/wubble
//
// Scores are reported, not asserted; the target is SSIM >= 0.95 per glyph.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as png from './lib/png.mjs';
import { ssim } from './lib/metrics.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const ui = resolve(here, '../../crates/wubble-ui/ui');
const CELL = 64, COLS = 8;
const GROUND = '#08090D', INK = '#F2F4FA'; // Palette.abyss, Palette.ink (gen/tokens.slint)
const CALL_SITES = [
  ['close', 12, 2, 'tab close (tabs.tsx:132)'], ['bubble', 13, 1.9, 'address (chrome.tsx:65)'],
  ['lock', 13, 1.9, 'address'], ['close', 8, 2.4, 'light'], ['minus', 8, 2.4, 'light'],
  ['expand', 8, 2.2, 'light'], ['plus', 15, 2, 'new tab (chrome.tsx:292)'], ['chevron-down', 14, 2, 'source panel'],
];

/** Property tables of a `.slint` file: group -> name -> path expression. */
function tables(text) {
  const out = {};
  let group = null;
  for (const line of text.split('\n')) {
    const g = line.match(/^export global (\w+)/);
    if (g) { group = g[1]; out[group] = {}; continue; }
    const p = line.match(/out property <string> ([\w-]+): (.+?);/);
    if (p && group) out[group][p[1]] = p[2];
  }
  return out;
}
const all = { ...tables(readFileSync(`${ui}/kit/gen/icons.slint`, 'utf8')), ...tables(readFileSync(`${ui}/kit/derived.slint`, 'utf8')) };
const glyphs = tables(readFileSync(`${ui}/kit/controls/icon.slint`, 'utf8')).Glyph;
const resolveExpr = e => e.split('+').map(t => t.trim()).map(t => {
  if (t.startsWith('"')) return t.slice(1, -1);
  const [g, n] = t.split('.');
  return resolveExpr(all[g][n]);
}).join('');
const paths = Object.fromEntries(Object.entries(glyphs).map(([n, e]) => [n, resolveExpr(e)]));

const cells = [];
const add = (name, size, stroke, note) => {
  const i = cells.length, x = (i % COLS) * CELL, y = Math.floor(i / COLS) * CELL;
  const off = Math.floor((CELL - size) / 2);
  cells.push({ id: `${name}@${size}/${stroke}`, name, size, stroke, note, path: paths[name], cell: [x, y, CELL, CELL], at: [x + off, y + off] });
};
for (const name of Object.keys(paths)) { add(name, 16, 1.7); add(name, 20, 1.7); }
for (const [name, size, stroke, note] of CALL_SITES) add(name, size, stroke, note);
const rows = Math.ceil(cells.length / COLS);
const SIZE = [COLS * CELL, rows * CELL];

function emit(dir) {
  const slint = `// generated by tools/fidelity/icon-sheet.mjs (node tools/fidelity/icon-sheet.mjs emit); do not edit
import { Palette } from "../ui/tokens.slint";
import { Icon, Glyph } from "../ui/kit/controls/icon.slint";

export component IconSheet inherits Window {
    width: ${SIZE[0]}px;
    height: ${SIZE[1]}px;
    background: Palette.abyss;
${cells.map(c => `    Icon { x: ${c.at[0]}px; y: ${c.at[1]}px; path: Glyph.${c.name}; size: ${c.size}px; weight: ${c.stroke}; tint: Palette.ink; }`).join('\n')}
}
`;
  writeFileSync(resolve(here, '../../crates/wubble-ui/tests/icon-sheet.slint'), slint);
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, 'cells.json'), JSON.stringify({ size: SIZE, cells }, null, 1));
  const html = `<!doctype html><meta charset=utf-8><body style="margin:0;background:${GROUND};color:${INK};width:${SIZE[0]}px;height:${SIZE[1]}px;position:relative;overflow:hidden">
${cells.map(c => `<svg style="position:absolute;left:${c.at[0]}px;top:${c.at[1]}px" width="${c.size}" height="${c.size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${c.stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="${c.path}"/></svg>`).join('\n')}
`;
  writeFileSync(resolve(dir, 'icon-sheet.html'), html);
  console.log(`icon-sheet: ${cells.length} cells (${new Set(cells.map(c => c.name)).size} glyphs), ${SIZE[0]}x${SIZE[1]}`);
}

async function web(dir) {
  const { launch } = await import('./lib/cdp.mjs');
  const page = await launch({ width: SIZE[0], height: SIZE[1] });
  try {
    for (const dpr of [1, 2]) {
      await page.send('Emulation.setDeviceMetricsOverride', { width: SIZE[0], height: SIZE[1], deviceScaleFactor: dpr, mobile: false });
      await page.send('Page.navigate', { url: `file://${resolve(dir, 'icon-sheet.html')}` });
      await new Promise(r => setTimeout(r, 400));
      const shot = await page.send('Page.captureScreenshot', { format: 'png', clip: { x: 0, y: 0, width: SIZE[0], height: SIZE[1], scale: 1 } });
      writeFileSync(resolve(dir, `web-${dpr}x.png`), Buffer.from(shot.data, 'base64'));
    }
  } finally { page.close(); }
}

/** The test's raw dump: u32 width, u32 height (little endian), RGBA. */
function readRaw(path) {
  const b = readFileSync(path);
  return { width: b.readUInt32LE(0), height: b.readUInt32LE(4), data: b.subarray(8) };
}

function score(dir) {
  const lines = ['| cell | 1x | 2x |', '|---|---|---|'];
  const worst = {};
  const by = {};
  for (const dpr of [1, 2]) {
    const a = png.read(resolve(dir, `web-${dpr}x.png`));
    const f = resolve(dir, `wubble-${dpr}x.rgba`);
    if (!existsSync(f)) throw new Error(`missing ${f}: run the icon_sheet test`);
    const b = readRaw(f);
    if (a.width !== b.width || a.height !== b.height) throw new Error(`size ${a.width}x${a.height} vs ${b.width}x${b.height}`);
    for (const c of cells) {
      const r = c.cell.map(v => v * dpr);
      (by[c.id] ??= {})[dpr] = ssim(png.crop(a, r), png.crop(b, r));
    }
    const sheet = png.hstack([a, b], 8);
    png.write(resolve(dir, `sheet-${dpr}x.png`), sheet);
  }
  for (const c of cells) lines.push(`| ${c.id}${c.note ? ' ' + c.note : ''} | ${by[c.id][1].toFixed(3)} | ${by[c.id][2].toFixed(3)} |`);
  const vals = d => cells.map(c => by[c.id][d]);
  const summary = d => `dpr ${d}: min ${Math.min(...vals(d)).toFixed(3)}, mean ${(vals(d).reduce((s, v) => s + v, 0) / cells.length).toFixed(3)}, ${vals(d).filter(v => v >= 0.95).length} of ${cells.length} cells >= 0.95`;
  lines.unshift(summary(1), summary(2), '');
  writeFileSync(resolve(dir, 'scores.md'), lines.join('\n') + '\n');
  console.log(lines.slice(0, 2).join('\n'));
}

const [cmd, dir = 'icon-sheet-out'] = process.argv.slice(2);
if (cmd === 'emit') emit(resolve(dir));
else if (cmd === 'web') await web(resolve(dir));
else if (cmd === 'score') score(resolve(dir));
else { console.error('usage: icon-sheet.mjs emit|web|score DIR'); process.exit(2); }
