/// A typed value as the text the `settings` table stores for it (the one encoding), for a
/// write through the generic text path (`Store::set_text`).
pub fn text_of<S: Setting>(value: &S::Value) -> String {
    Codec::encode(value)
}

impl Store {
    /// The setting's value, or its default if the row is absent or cannot be decoded.
    pub async fn setting<S: Setting>(&self) -> Result<S::Value> {
        Ok(self
            .get_raw(S::DEF.key)
            .await?
            .filter(|s| S::DEF.kind.accepts(s))
            .and_then(|s| <S::Value as Codec>::decode(&s))
            .unwrap_or_else(S::default))
    }

    pub async fn set_setting<S: Setting>(&mut self, value: S::Value) -> Result<()> {
        self.set_raw(S::DEF.key, &Codec::encode(&value)).await
    }

    /// Every stored row that is a setting of the table, `key -> text`, as stored (the page and
    /// `apply::effect_of` read an invalid one as the default).
    pub async fn all_settings(&self) -> Result<HashMap<String, String>> {
        let mut rows = self
            .conn
            .query("SELECT key, value FROM settings", ())
            .await?;
        let mut out = HashMap::new();
        while let Some(r) = rows.next().await? {
            let key: String = r.get(0)?;
            if defs::find(&key).is_some() {
                out.insert(key, r.get(1)?);
            }
        }
        Ok(out)
    }

    /// Stores `text` under the setting `key` (the settings page's generic write). A key that is
    /// no setting, or a value its kind refuses, is an error and leaves the row as it was.
    pub async fn set_text(&mut self, key: &str, text: &str) -> Result<()> {
        match defs::find(key) {
            Some(def) if def.kind.accepts(text) => self.set_raw(def.key, text).await,
            Some(_) => Err(crate::Error::Invalid(format!(
                "{text:?} is not a value of {key}"
            ))),
            None => Err(crate::Error::Invalid(format!("{key} is not a setting"))),
        }
    }

    pub(crate) async fn get_raw(&self, key: &str) -> Result<Option<String>> {
        let mut rows = self
            .conn
            .query("SELECT value FROM settings WHERE key = ?1", [key])
            .await?;
        Ok(match rows.next().await? {
            Some(r) => Some(r.get(0)?),
            None => None,
        })
    }

    async fn set_raw(&mut self, key: &str, value: &str) -> Result<()> {
        self.conn
            .execute(
                "INSERT INTO settings(key, value) VALUES (?1, ?2) \
                 ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                (key, value),
            )
            .await?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use wubble_core::seam::SIDEBAR_DEFAULT;

    fn run<F: std::future::Future>(f: F) -> F::Output {
        pollster::block_on(f)
    }

    async fn round_trip<S: Setting>(s: &mut Store, v: S::Value)
    where
        S::Value: PartialEq + std::fmt::Debug + Clone,
    {
        s.set_setting::<S>(v.clone()).await.unwrap();
        assert_eq!(s.setting::<S>().await.unwrap(), v);
    }

    #[test]
    fn every_setting_has_its_default_on_a_fresh_store() {
        run(async {
            let s = Store::open_in_memory().await.unwrap();
            assert_eq!(s.setting::<SearchEngineChoice>().await.unwrap(), None);
            assert!(!s.setting::<LiveSuggestions>().await.unwrap());
            assert_eq!(
                s.setting::<SidebarWidth>().await.unwrap(),
                SIDEBAR_DEFAULT as f32
            );
            assert_eq!(
                s.setting::<SidebarModeSetting>().await.unwrap(),
                SidebarMode::Extended
            );
            assert!(s.setting::<KeybindingOverrides>().await.unwrap().is_empty());
            assert!(s.setting::<BlockerEnabled>().await.unwrap());
            assert!(s.setting::<BlockerExceptions>().await.unwrap().is_empty());
            assert!(s.setting::<SiteZoom>().await.unwrap().is_empty());
            assert!(!s.setting::<BlockerListsAutoUpdate>().await.unwrap());
            assert_eq!(s.setting::<HistoryRetentionDays>().await.unwrap(), 0);
        });
    }

    #[test]
    fn values_round_trip_and_overwrite() {
        run(async {
            let mut s = Store::open_in_memory().await.unwrap();
            round_trip::<SearchEngineChoice>(&mut s, Some(SearchEngine::DuckDuckGo)).await;
            round_trip::<SearchEngineChoice>(&mut s, Some(SearchEngine::Google)).await;
            round_trip::<SearchEngineChoice>(&mut s, None).await;
            round_trip::<LiveSuggestions>(&mut s, true).await;
            round_trip::<LiveSuggestions>(&mut s, false).await;
            round_trip::<SidebarWidth>(&mut s, 312.5).await;
            for mode in [
                SidebarMode::Hidden,
                SidebarMode::Rail,
                SidebarMode::Extended,
            ] {
                round_trip::<SidebarModeSetting>(&mut s, mode).await;
            }
            round_trip::<HistoryRetentionDays>(&mut s, 90).await;
            round_trip::<BlockerEnabled>(&mut s, false).await;
            round_trip::<BlockerListsAutoUpdate>(&mut s, true).await;
            let list = |v: &[&str]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
            round_trip::<KeybindingOverrides>(&mut s, list(&["a,b", "say \"hi\"", "ctrl+ü", ""]))
                .await;
            round_trip::<KeybindingOverrides>(&mut s, vec![]).await;
            round_trip::<BlockerExceptions>(&mut s, list(&["example.com", "日本.jp"])).await;
            let zoom = ZoomTable::from([("a.test".to_string(), 125), ("日本.jp".to_string(), 67)]);
            round_trip::<SiteZoom>(&mut s, zoom).await;
            round_trip::<SiteZoom>(&mut s, ZoomTable::new()).await;
        });
    }

    #[test]
    fn undecodable_rows_yield_the_default() {
        run(async {
            let mut s = Store::open_in_memory().await.unwrap();
            s.set_raw(LiveSuggestions::DEF.key, "maybe").await.unwrap();
            s.set_raw(SidebarWidth::DEF.key, "wide").await.unwrap();
            s.set_raw(SearchEngineChoice::DEF.key, "bing")
                .await
                .unwrap();
            s.set_raw(BlockerExceptions::DEF.key, "{not a list")
                .await
                .unwrap();
            s.set_raw(BlockerEnabled::DEF.key, "").await.unwrap();
            s.set_raw(HistoryRetentionDays::DEF.key, "-3")
                .await
                .unwrap();
            s.set_raw(SidebarModeSetting::DEF.key, "peeking")
                .await
                .unwrap();
            s.set_raw(SiteZoom::DEF.key, "{\"a.test\": -5}")
                .await
                .unwrap();
            assert!(s.setting::<SiteZoom>().await.unwrap().is_empty());
            assert_eq!(
                s.setting::<SidebarModeSetting>().await.unwrap(),
                SidebarMode::Extended
            );
            assert_eq!(s.setting::<HistoryRetentionDays>().await.unwrap(), 0);
            assert!(!s.setting::<LiveSuggestions>().await.unwrap());
            assert_eq!(
                s.setting::<SidebarWidth>().await.unwrap(),
                SIDEBAR_DEFAULT as f32
            );
            assert_eq!(s.setting::<SearchEngineChoice>().await.unwrap(), None);
            assert!(s.setting::<BlockerExceptions>().await.unwrap().is_empty());
            assert!(s.setting::<BlockerEnabled>().await.unwrap());
        });
    }

    #[test]
    fn set_text_validates_and_all_settings_reads_back() {
        run(async {
            let mut s = Store::open_in_memory().await.unwrap();
            assert!(s.all_settings().await.unwrap().is_empty());
            s.set_text("blocker.enabled", "0").await.unwrap();
            s.set_text("glass.quality", "reduced").await.unwrap();
            assert!(s.set_text("blocker.enabled", "maybe").await.is_err());
            assert!(s.set_text("zoom.default", "9000").await.is_err());
            assert!(s.set_text("no.such", "1").await.is_err());
            assert!(!s.setting::<BlockerEnabled>().await.unwrap());
            assert_eq!(
                s.setting::<GlassQuality>().await.unwrap(),
                GlassSetting::Reduced
            );
            s.set_raw("not.a.setting", "x").await.unwrap();
            let all = s.all_settings().await.unwrap();
            assert_eq!(all.len(), 2);
            assert_eq!(all["blocker.enabled"], "0");
            // The typed write and the text write are one row.
            s.set_setting::<ZoomDefault>(125).await.unwrap();
            assert_eq!(s.all_settings().await.unwrap()["zoom.default"], "125");
        });
    }

    #[test]
    fn typed_settings_are_exactly_the_core_table() {
        let typed: Vec<&str> = typed().iter().map(|(d, _)| d.key).collect();
        let table: Vec<&str> = defs::ALL.iter().map(|d| d.key).collect();
        assert_eq!(typed, table);
    }

    #[test]
    fn every_default_is_valid_and_decodes() {
        for (def, decodes) in typed() {
            assert!(def.kind.accepts(def.default), "{} default invalid", def.key);
            assert!(decodes(def.default), "{} default does not decode", def.key);
        }
    }

    #[test]
    fn legacy_key_strings_and_flag_format_are_kept() {
        run(async {
            let mut s = Store::open_in_memory().await.unwrap();
            s.set_setting::<SearchEngineChoice>(Some(SearchEngine::Google))
                .await
                .unwrap();
            s.set_setting::<LiveSuggestions>(true).await.unwrap();
            assert_eq!(
                s.get_raw("search.engine").await.unwrap().as_deref(),
                Some("google")
            );
            assert_eq!(
                s.get_raw("suggest.live").await.unwrap().as_deref(),
                Some("1")
            );
            s.set_setting::<LiveSuggestions>(false).await.unwrap();
            assert_eq!(
                s.get_raw("suggest.live").await.unwrap().as_deref(),
                Some("0")
            );
            s.set_raw("search.engine", "duckduckgo").await.unwrap();
            assert_eq!(
                s.setting::<SearchEngineChoice>().await.unwrap(),
                Some(SearchEngine::DuckDuckGo)
            );
        });
    }
}
