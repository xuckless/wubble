//! Typed settings over the key/value `settings` table, defined once in the `settings!` table
//! below as (name, type, key, default). Values are text; each type has one [`Codec`].
//!
//! Design reference, no code copied: Chromium's pref registration (a path, a type and a default
//! per pref, e.g. `RegisterBooleanPref`), BSD-3-Clause.
//!
//! A missing or undecodable row yields the default: a bad settings row must not block startup.

use wubble_core::omnibox::SearchEngine;

use crate::{Result, Store};

/// Text form of a setting value.
trait Codec: Sized {
    fn encode(&self) -> String;
    fn decode(s: &str) -> Option<Self>;
}

/// One setting: a zero-sized type generated by `settings!`.
#[allow(private_bounds)]
pub trait Setting {
    type Value: Codec;
    const KEY: &'static str;
    fn default() -> Self::Value;
}

impl Codec for bool {
    fn encode(&self) -> String {
        if *self { "1" } else { "0" }.into()
    }
    fn decode(s: &str) -> Option<Self> {
        match s {
            "1" => Some(true),
            "0" => Some(false),
            _ => None,
        }
    }
}

impl Codec for u32 {
    fn encode(&self) -> String {
        self.to_string()
    }
    fn decode(s: &str) -> Option<Self> {
        s.parse().ok()
    }
}

impl Codec for f32 {
    fn encode(&self) -> String {
        self.to_string()
    }
    fn decode(s: &str) -> Option<Self> {
        s.parse().ok().filter(|v: &f32| v.is_finite())
    }
}

/// `None` (ask on first run) is the empty string.
impl Codec for Option<SearchEngine> {
    fn encode(&self) -> String {
        match self {
            None => "",
            Some(SearchEngine::Google) => "google",
            Some(SearchEngine::DuckDuckGo) => "duckduckgo",
        }
        .into()
    }
    fn decode(s: &str) -> Option<Self> {
        match s {
            "" => Some(None),
            "google" => Some(Some(SearchEngine::Google)),
            "duckduckgo" => Some(Some(SearchEngine::DuckDuckGo)),
            _ => None,
        }
    }
}

/// A JSON array of strings; entries are opaque to the store.
impl Codec for Vec<String> {
    fn encode(&self) -> String {
        serde_json::to_string(self).expect("a string list always serialises")
    }
    fn decode(s: &str) -> Option<Self> {
        serde_json::from_str(s).ok()
    }
}

macro_rules! settings {
    ($($(#[$doc:meta])* $name:ident: $ty:ty = $key:literal, $default:expr;)*) => {
        $(
            $(#[$doc])*
            pub struct $name;
            impl Setting for $name {
                type Value = $ty;
                const KEY: &'static str = $key;
                fn default() -> $ty { $default }
            }
        )*
        /// Every key in the table, for the uniqueness test.
        #[cfg(test)]
        const ALL_KEYS: &[&str] = &[$($key),*];
    };
}

settings! {
    /// `None` = ask on first run.
    SearchEngineChoice: Option<SearchEngine> = "search.engine", None;
    /// Live engine suggestions; off until the user turns them on.
    LiveSuggestions: bool = "suggest.live", false;
    /// Logical pixels; matches `Sizes.sidebar-width` in the UI tokens.
    SidebarWidth: f32 = "ui.sidebar_width", 260.0;
    CompactMode: bool = "ui.compact", false;
    /// Opaque entries; the keybinding editor owns their format.
    KeybindingOverrides: Vec<String> = "keys.overrides", vec![];
    BlockerEnabled: bool = "blocker.enabled", true;
    /// Hosts the blocker skips.
    BlockerExceptions: Vec<String> = "blocker.exceptions", vec![];
    /// Visits older than this many days are expired by `Store::expire_history`; 0 keeps everything.
    HistoryRetentionDays: u32 = "history.retention_days", 0;
}

impl Store {
    /// The setting's value, or its default if the row is absent or cannot be decoded.
    pub async fn setting<S: Setting>(&self) -> Result<S::Value> {
        Ok(self
            .get_raw(S::KEY)
            .await?
            .and_then(|s| <S::Value as Codec>::decode(&s))
            .unwrap_or_else(S::default))
    }

    pub async fn set_setting<S: Setting>(&mut self, value: S::Value) -> Result<()> {
        self.set_raw(S::KEY, &Codec::encode(&value)).await
    }

    async fn get_raw(&self, key: &str) -> Result<Option<String>> {
        let mut rows = self
            .conn
            .query("SELECT value FROM settings WHERE key = ?1", [key])
            .await?;
        Ok(match rows.next().await? {
            Some(r) => Some(r.get(0)?),
            None => None,
        })
    }

    async fn set_raw(&mut self, key: &str, value: &str) -> Result<()> {
        self.conn
            .execute(
                "INSERT INTO settings(key, value) VALUES (?1, ?2) \
                 ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                (key, value),
            )
            .await?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn run<F: std::future::Future>(f: F) -> F::Output {
        pollster::block_on(f)
    }

    async fn round_trip<S: Setting>(s: &mut Store, v: S::Value)
    where
        S::Value: PartialEq + std::fmt::Debug + Clone,
    {
        s.set_setting::<S>(v.clone()).await.unwrap();
        assert_eq!(s.setting::<S>().await.unwrap(), v);
    }

    #[test]
    fn every_setting_has_its_default_on_a_fresh_store() {
        run(async {
            let s = Store::open_in_memory().await.unwrap();
            assert_eq!(s.setting::<SearchEngineChoice>().await.unwrap(), None);
            assert!(!s.setting::<LiveSuggestions>().await.unwrap());
            assert_eq!(s.setting::<SidebarWidth>().await.unwrap(), 260.0);
            assert!(!s.setting::<CompactMode>().await.unwrap());
            assert!(s.setting::<KeybindingOverrides>().await.unwrap().is_empty());
            assert!(s.setting::<BlockerEnabled>().await.unwrap());
            assert!(s.setting::<BlockerExceptions>().await.unwrap().is_empty());
        });
    }

    #[test]
    fn values_round_trip_and_overwrite() {
        run(async {
            let mut s = Store::open_in_memory().await.unwrap();
            round_trip::<SearchEngineChoice>(&mut s, Some(SearchEngine::DuckDuckGo)).await;
            round_trip::<SearchEngineChoice>(&mut s, Some(SearchEngine::Google)).await;
            round_trip::<SearchEngineChoice>(&mut s, None).await;
            round_trip::<LiveSuggestions>(&mut s, true).await;
            round_trip::<LiveSuggestions>(&mut s, false).await;
            round_trip::<SidebarWidth>(&mut s, 312.5).await;
            round_trip::<CompactMode>(&mut s, true).await;
            round_trip::<HistoryRetentionDays>(&mut s, 90).await;
            round_trip::<BlockerEnabled>(&mut s, false).await;
            let list = |v: &[&str]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
            round_trip::<KeybindingOverrides>(&mut s, list(&["a,b", "say \"hi\"", "ctrl+ü", ""]))
                .await;
            round_trip::<KeybindingOverrides>(&mut s, vec![]).await;
            round_trip::<BlockerExceptions>(&mut s, list(&["example.com", "日本.jp"])).await;
        });
    }

    #[test]
    fn undecodable_rows_yield_the_default() {
        run(async {
            let mut s = Store::open_in_memory().await.unwrap();
            s.set_raw(LiveSuggestions::KEY, "maybe").await.unwrap();
            s.set_raw(SidebarWidth::KEY, "wide").await.unwrap();
            s.set_raw(SearchEngineChoice::KEY, "bing").await.unwrap();
            s.set_raw(BlockerExceptions::KEY, "{not a list")
                .await
                .unwrap();
            s.set_raw(BlockerEnabled::KEY, "").await.unwrap();
            s.set_raw(HistoryRetentionDays::KEY, "-3").await.unwrap();
            assert_eq!(s.setting::<HistoryRetentionDays>().await.unwrap(), 0);
            assert!(!s.setting::<LiveSuggestions>().await.unwrap());
            assert_eq!(s.setting::<SidebarWidth>().await.unwrap(), 260.0);
            assert_eq!(s.setting::<SearchEngineChoice>().await.unwrap(), None);
            assert!(s.setting::<BlockerExceptions>().await.unwrap().is_empty());
            assert!(s.setting::<BlockerEnabled>().await.unwrap());
        });
    }

    #[test]
    fn keys_are_unique() {
        for (i, k) in ALL_KEYS.iter().enumerate() {
            assert!(!ALL_KEYS[..i].contains(k), "duplicate key {k}");
        }
    }

    #[test]
    fn legacy_key_strings_and_flag_format_are_kept() {
        run(async {
            let mut s = Store::open_in_memory().await.unwrap();
            s.set_setting::<SearchEngineChoice>(Some(SearchEngine::Google))
                .await
                .unwrap();
            s.set_setting::<LiveSuggestions>(true).await.unwrap();
            assert_eq!(
                s.get_raw("search.engine").await.unwrap().as_deref(),
                Some("google")
            );
            assert_eq!(
                s.get_raw("suggest.live").await.unwrap().as_deref(),
                Some("1")
            );
            s.set_setting::<LiveSuggestions>(false).await.unwrap();
            assert_eq!(
                s.get_raw("suggest.live").await.unwrap().as_deref(),
                Some("0")
            );
            s.set_raw("search.engine", "duckduckgo").await.unwrap();
            assert_eq!(
                s.setting::<SearchEngineChoice>().await.unwrap(),
                Some(SearchEngine::DuckDuckGo)
            );
        });
    }
}
