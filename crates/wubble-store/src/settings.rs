/// Text form of a setting value.
trait Codec: Sized {
    fn encode(&self) -> String;
    fn decode(s: &str) -> Option<Self>;
}

/// One setting: a zero-sized type generated by `settings!`.
#[allow(private_bounds)]
pub trait Setting {
    type Value: Codec;
    const DEF: &'static defs::SettingDef;
    fn default() -> Self::Value;
}

impl Codec for bool {
    fn encode(&self) -> String {
        if *self { "1" } else { "0" }.into()
    }
    fn decode(s: &str) -> Option<Self> {
        match s {
            "1" => Some(true),
            "0" => Some(false),
            _ => None,
        }
    }
}

impl Codec for u32 {
    fn encode(&self) -> String {
        self.to_string()
    }
    fn decode(s: &str) -> Option<Self> {
        s.parse().ok()
    }
}

impl Codec for f32 {
    fn encode(&self) -> String {
        self.to_string()
    }
    fn decode(s: &str) -> Option<Self> {
        s.parse().ok().filter(|v: &f32| v.is_finite())
    }
}

/// `None` (ask on first run) is the empty string; engines use their `EngineInfo::id`.
impl Codec for Option<SearchEngine> {
    fn encode(&self) -> String {
        self.map_or("", SearchEngine::id).into()
    }
    fn decode(s: &str) -> Option<Self> {
        if s.is_empty() {
            Some(None)
        } else {
            SearchEngine::from_id(s).map(Some)
        }
    }
}

/// A choice stored as its word (`id`, `from_id`).
macro_rules! word_codec {
    ($($ty:ty),* $(,)?) => {$(
        impl Codec for $ty {
            fn encode(&self) -> String {
                self.id().into()
            }
            fn decode(s: &str) -> Option<Self> {
                <$ty>::from_id(s)
            }
        }
    )*};
}

word_codec!(
    SidebarMode,
    GlassSetting,
    PageTheme,
    Motion,
    Contrast,
    ReaderWidth,
    ReaderFont,
    ReaderTheme,
    ShotOutput,
);

/// A word of a choice the store has no type for (the core table checks it).
impl Codec for String {
    fn encode(&self) -> String {
        self.clone()
    }
    fn decode(s: &str) -> Option<Self> {
        Some(s.to_owned())
    }
}

impl Codec for ArchiveAfter {
    fn encode(&self) -> String {
        self.id().into()
    }
    fn decode(s: &str) -> Option<Self> {
        ArchiveAfter::from_id(s)
    }
}

/// A JSON array of strings; entries are opaque to the store.
impl Codec for defs::BackForwardCache {
    fn encode(&self) -> String {
        self.word().into()
    }
    fn decode(s: &str) -> Option<Self> {
        Self::from_word(s)
    }
}

impl Codec for Vec<String> {
    fn encode(&self) -> String {
        serde_json::to_string(self).expect("a string list always serialises")
    }
    fn decode(s: &str) -> Option<Self> {
        serde_json::from_str(s).ok()
    }
}

/// A JSON object of host to zoom percent.
impl Codec for ZoomTable {
    fn encode(&self) -> String {
        serde_json::to_string(self).expect("a string-to-number map always serialises")
    }
    fn decode(s: &str) -> Option<Self> {
        serde_json::from_str(s).ok()
    }
}

macro_rules! settings {
    ($($(#[$doc:meta])* $name:ident: $ty:ty = $def:expr;)*) => {
        $(
            $(#[$doc])*
            pub struct $name;
            impl Setting for $name {
                type Value = $ty;
                const DEF: &'static defs::SettingDef = &$def;
                fn default() -> $ty {
                    <$ty as Codec>::decode($def.default)
                        .expect("a core settings default decodes with its codec")
                }
            }
        )*
        /// Each typed setting's core definition, for the table-agreement tests.
        #[cfg(test)]
        fn typed() -> Vec<(&'static defs::SettingDef, fn(&str) -> bool)> {
            vec![$((&$def, |s| <$ty as Codec>::decode(s).is_some())),*]
        }
    };
}

